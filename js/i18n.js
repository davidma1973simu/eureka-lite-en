  function t(key, fallback) {
    // 铁律：EN 模式下绝不显示中文。
    // - en 模式：返回 dict.en[key]；缺失时返回英文占位 "[key]"，绝不回退中文 fallback。
    // - zh 模式：直接返回 fallback（原中文），保证界面与国际化前字节一致。
    if (current === 'en') {
      var val = dict.en[key];
      if (val !== undefined && val !== null && val !== '') return val;
      // 未翻译 → 返回 key 占位（宁可见 key，不见中文）
      return '[' + key + ']';
    }
    return (fallback !== undefined) ? fallback : key;
  }

